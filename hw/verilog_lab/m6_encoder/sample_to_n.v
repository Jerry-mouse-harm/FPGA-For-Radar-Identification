// 手撕练习：定点样本 → 脉冲数 n（脉冲编码前端 · 之一）—— 自己补全实现
//
// 干什么用的：SNN 的第一步。硬件从 BRAM 拿出实数样本（项目里是 128 个），每个样本要先
//             翻译成"这 T=16 步里该发几个脉冲"（0..16 的整数），下一级 ΣΔ 单元再把这个数
//             摊成脉冲序列。**这个映射必须和训练时一模一样**
//             —— LOG.md 的铁律：编码域不一致会掉 24~40pp；同域下脉冲化本身只掉 0.7pp。
//
// 训练端原话（src/models/snn_conv.py :: encode_input, mode='spread'）：
//       x01 = clamp(x/inv_scale + 0.5, 0, 1)        inv_scale = 8
//       n   = round(x01 * T)                        T = 16
//   硬件把 x 定成 1/16 分辨率的定点（x = din/16），代进去就只剩整数运算：
//       n = round(din/8 + 8)        ← 没有乘法、没有浮点
//
// 规格（判分台严格按这个来）：
//   1) 纯组合，没有时钟（本质就是个解码器）
//   2) din 是有符号定点样本，x = din/16；din = ±64 对应 x = ±4，正好是训练端 clamp 的两端
//   3) 定点三步（顺序不能换）：
//        加半个 LSB： din + 4        // 4 = 2³/2；先加再右移 == 四舍五入
//        除以 8：     (din+4) >>> 3   // >>> 是**算术**右移（负数补 1，不是补 0）
//        抬到区间：   + T/2          // 8，把 [-8,+8] 平移到中心 8
//   4) 最后钳位到 [0, T]：超上界给 16，超下界给 0
//      （训练端的 clamp(x/8+0.5,0,1) 落到这里就是这两条：样本超 ±4 必须饱和）
//
// 记忆套路：
//   "定点除法 + 四舍五入 + 饱和"三件套，一行一个：
//     · 必须写 >>> 而不是 >>  —— 右移负数时 >> 补 0，负数会变成一个大正数
//     · 比较顺序先判 <0 再判 >T —— >T 的两边一个有符号一个无符号，先把负数摘掉，
//       剩下的就永远是"两边都非负"的干净比较
//
// 自检锚点（拿判分台向量对）：
//     din =   0 → n =  8     x=0，正好在中心（x01=0.5）
//     din =  32 → n = 12     x=2（x01=0.75）
//     din =  64 → n = 16     x=4，顶到上限 → 16 步全发
//     din = -64 → n =  0     x=-4，底到下限 → 一个都不发
//     din = 127 → n = 16     溢出样本必须饱和，不是 24
//
// ⚠ 一个已知的、可忽略的差异（将来做全量对拍时会遇到，先记着）：
//   训练端 torch.round 是"银行家舍入"（.5 进偶），硬件"加半 LSB"是 .5 进上。
//   只有 din ≡ 4 (mod 8) 时 n 会差 1（16 步里差 1 个脉冲 ≈ 6% 电荷，且只发生在 1/8 的样本上）。
//   判分台的金标准向量**刻意避开了这些点**，所以两种舍入都能过；
//   真要逐位对上浮点，就在这儿加一句".5 且当前是奇数时减 1"。
//
