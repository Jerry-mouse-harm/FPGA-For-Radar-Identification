// 手撕练习：ΣΔ 脉冲编码单元（脉冲编码前端 · 之二）—— 自己补全实现
//
// 干什么用的：把 sample_to_n 算出来的 n 摊成 T=16 步的 0/1 脉冲序列。
//             训练端管这叫 spread 编码，硬件实现只要"一个累加器 + 一个比较器"。
//             （对比 rate 编码 s[t]=(t<n)：电荷全挤在前 n 步，t=0 全体起爆、瞬时电流冲击大；
//               spread 把 n 个脉冲均匀铺满 16 步，接近恒流。同域公平对比下 spread 高 ~2.2pp）
//
// 训练端原话（src/models/snn_conv.py :: encode_input, mode='spread'）：
//       acc = 0
//       for t in 0..T-1:
//           acc += n
//           s[t] = (acc >= T)
//           if s[t]: acc -= T
//   闭式等价：s[t] = floor((t+1)·n/T) - floor(t·n/T)   ← 硬件只用左边的累加器版
//
// 规格（判分台严格按这个来，拍数不能差）：
//   1) 异步复位低有效：acc=0, step=0, spike=0
//   2) load 高 1 拍：**这一拍只做载入**（acc<=0, step<=0, spike<=0），不发脉冲；
//      从 load 的**下一拍**起依次是第 0、1、…、15 步
//   3) 第 t 步（t = 0..15）：
//        若 acc >= T-n  → spike <= 1，acc <= acc - (T-n)
//        否则           → spike <= 0，acc <= acc + n
//   4) 走完 16 步后 spike 保持 0，直到下一次 load
//   5) 中途重载也要能立刻从头开始（load 必须把 acc / step 一起清掉）
//
// 记忆套路：
//   · 比较写 `acc >= T-n` 而**不是** `acc + n >= T`：acc、n 都 ≤ 16，换个写法两边都 ≤16，
//     位宽怎么都不会溢出；而 acc+n 最大到 31，一不小心就少了一位。
//     （判分台里"忘了加 n"写成 `acc >= T` 的经典错法就是在这露馅的）
//   · acc / step 都 5 位：0..15 是有效值，step 还要能到 16 表示"走完了"
//   · 只用一个计数器区分"正在发 / 发完了"，不需要写成状态机（别什么模块都写成三段式）
//
// 自检锚点（写之前先背下来，心里有数）：
//     n = 0  → 0000_0000_0000_0000   一个都不发
//     n = 8  → 1010_1010_1010_1010   隔一步发一次（Bresenham 的直觉）
//     n = 16 → 1111_1111_1111_1111   每步都发
//     n = 1  → 1000_0000_0000_0000   单个脉冲落在**最后一步**，不是第一步！
//     n = 15 → 1111_1111_1111_1110   只有第 0 步不发
//   位序约定：图案的 bit t 就是第 t 步（bit0 = 第 0 步）
//
